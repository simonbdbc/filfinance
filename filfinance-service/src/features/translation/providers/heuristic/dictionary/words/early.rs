//! Traductions heuristiques des mots de debut d'alphabet.

/// Traduit les mots de `after` a `futures`.
pub(super) fn translate_early_word(core: &str) -> Option<&'static str> {
    match core {
        "after" => Some("apres"),
        "ahead" => Some("avant"),
        "amid" => Some("dans"),
        "analyst" => Some("analyste"),
        "analysts" => Some("analystes"),
        "as" => Some("alors que"),
        "at" => Some("a"),
        "bank" => Some("banque"),
        "banks" => Some("banques"),
        "beats" => Some("depasse"),
        "below" => Some("sous"),
        "bond" => Some("obligation"),
        "bonds" => Some("obligations"),
        "bullish" => Some("haussier"),
        "cautions" => Some("alerte"),
        "claims" => Some("allocations"),
        "cuts" => Some("baisses"),
        "cut" => Some("baisse"),
        "data" => Some("donnees"),
        "decline" => Some("recul"),
        "declines" => Some("recule"),
        "dips" => Some("recule"),
        "dollar" => Some("dollar"),
        "earnings" => Some("resultats"),
        "eases" => Some("ralentit"),
        "easing" => Some("assouplissement"),
        "elevated" => Some("eleves"),
        "employment" => Some("emploi"),
        "euro" => Some("euro"),
        "falls" => Some("recule"),
        "fall" => Some("recul"),
        "fed" => Some("Fed"),
        "fiscal" => Some("budgetaire"),
        "focus" => Some("attention"),
        "forecast" => Some("prevision"),
        "forecasts" => Some("previsions"),
        "futures" => Some("futures"),
        _ => None,
    }
}
